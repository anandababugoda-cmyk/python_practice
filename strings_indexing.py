
# Python Strings and Indexing

# String declaration
name = "Anand Babu"

# Display string
print("Original String:", name)

# Positive indexing
print("First Character:", name[0])
print("Second Character:", name[1])

# Negative indexing
print("Last Character:", name[-1])
print("Second Last Character:", name[-2])

# String slicing
print("First Five Characters:", name[0:5])
print("From Index 6:", name[6:])

# String length
print("String Length:", len(name))

# String methods
print("Uppercase:", name.upper())
print("Lowercase:", name.lower())
print("Title Case:", name.title())

# Reverse string
print("Reverse:", name[::-1])
